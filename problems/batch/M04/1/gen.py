def ri(lo, hi):
    return lo + int(random.random() * (hi - lo + 1))


def add(r, c):
    n, q = len(r), len(c)
    assert 1 <= n <= MAXN and 1 <= q <= MAXQ
    assert all(-MAXR <= x <= MAXR for x in r)
    assert all(1 <= x <= MAXC for x in c)
    tests.append(f"{n} {q}\n" + " ".join(map(str, r)) + "\n" + " ".join(map(str, c)) + "\n")


def targets(r, q, at, miss=0.1, near=0.5):
    total = list(accumulate(r))
    marks = [total[i] for i in at]
    top = max(1, marks[-1])
    res = []
    for _ in range(q):
        t = random.random()
        if t < miss:
            v = ri(top + 1, min(MAXC, top + 10**12)) if top < MAXC else MAXC
        elif t < miss + near:
            v = marks[ri(max(0, len(marks) - 1 - ri(0, 50)), len(marks) - 1)] + ri(-1, 1)
        else:
            v = ri(1, top)
        res.append(min(MAXC, max(1, v)))
    return res


